#!/usr/bin/env bash
#
# Fail if text inside an unquoted heredoc would be run by the shell instead of written out.
#
# ## Why this exists
#
# `install-node.sh` writes its config files from unquoted heredocs (`<<EOF`), because the
# values in them are interpolated. In an unquoted heredoc a backtick is command substitution —
# everywhere, including on lines that are comments in the file being written. Fifteen comment
# lines used Markdown-style backticks to name a setting, so a fresh install ran `enabled`,
# `port`, `secret`, `pool_sv2` and eleven more words as commands, as root, printed a wall of
# "command not found" under "Writing /etc/ghost/pool.toml", exited 0, and left config files
# whose comments had a hole exactly where each setting was named (#1027).
#
# Nothing caught it: `bash -n` accepts it, shellcheck accepts it, and every existing check
# reads the installer as text. It showed up the first time the installer was run on a clean
# machine.
#
# ## What it checks
#
# In every tracked shell script, inside every heredoc whose delimiter is NOT quoted: a backtick
# that is not escaped, on any line.
#
# `$(...)` is how these heredocs interpolate, and is deliberate even on a comment line
# ("# Generated by installer on $(date)"), so it is left alone; nobody writes command
# substitution with backticks on purpose in a file that also uses them as Markdown. A quoted
# heredoc (`<<'EOF'`) is written out verbatim and is skipped whole, including any heredoc
# nested in the script it contains — that script is checked as its own file where it lives.
#
# To write a literal backtick in an unquoted heredoc, escape it: \`
#
# Exit 0 = nothing would run, 1 = something would, 2 = INCONCLUSIVE (the scan found no heredocs,
# or could not see its own planted case, so its silence would mean nothing).
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT" || exit 2

python3 - "$@" <<'PY'
import re, subprocess, sys

START = re.compile(r"(?<!<)<<(-?)\s*(\\?)(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\3")
UNESCAPED_TICK = re.compile(r"(?<!\\)(?:\\\\)*`")


def scan(text):
    """Return ([(heredoc_start_line, line_no, text)], unquoted heredocs, lines examined)."""
    lines = text.split("\n")
    findings, heredocs, examined = [], 0, 0
    i = 0
    while i < len(lines):
        line = lines[i]
        # A `#` comment line in the script itself cannot open a heredoc.
        m = None if line.lstrip().startswith("#") else START.search(line)
        if not m:
            i += 1
            continue
        strip_tabs, quoted, tag = bool(m.group(1)), bool(m.group(2) or m.group(3)), m.group(4)
        start = i
        i += 1
        if not quoted:
            heredocs += 1
        while i < len(lines):
            body = lines[i].lstrip("\t") if strip_tabs else lines[i]
            if body == tag:
                break
            if not quoted:
                examined += 1
                if UNESCAPED_TICK.search(lines[i]):
                    findings.append((start + 1, i + 1, lines[i].strip()))
            i += 1
        i += 1
    return findings, heredocs, examined


# --- the scan must be able to see what it is looking for --------------------------------------
planted = "cat > f <<EOF\n# set `port` here\n# built $(date)\nvalue = $(hostname)\n# escaped \\`ok\\`\nEOF\ncat <<'Q'\n# `fine`\nQ\n"
found, n, _ = scan(planted)
if [f[1] for f in found] != [2] or n != 1:
    print(f"check-heredoc-comments-are-inert: INCONCLUSIVE — the planted case read as {found!r}", file=sys.stderr)
    sys.exit(2)

files = sys.argv[1:] or subprocess.run(
    ["git", "ls-files", "*.sh"], capture_output=True, text=True, check=True
).stdout.split()

bad, total_heredocs, total_lines, scanned = [], 0, 0, 0
for path in files:
    try:
        text = open(path, encoding="utf-8", errors="replace").read()
    except OSError:
        continue
    scanned += 1
    found, n, examined = scan(text)
    total_heredocs += n
    total_lines += examined
    bad += [(path,) + f for f in found]

if total_heredocs == 0:
    print("check-heredoc-comments-are-inert: INCONCLUSIVE — no unquoted heredoc found in "
          f"{scanned} script(s); the scan is looking at nothing", file=sys.stderr)
    sys.exit(2)

if bad:
    print("Text in an unquoted heredoc would be RUN by the shell, not written out:\n", file=sys.stderr)
    for path, start, line, text in bad:
        print(f"  {path}:{line}  (heredoc opened at line {start})", file=sys.stderr)
        print(f"      {text[:110]}", file=sys.stderr)
    print(f"\n{len(bad)} line(s). Escape a literal backtick as \\` — or quote the heredoc "
          "delimiter if nothing in it is interpolated.", file=sys.stderr)
    sys.exit(1)

print(f"check-heredoc-comments-are-inert: {total_lines} line(s) in {total_heredocs} unquoted "
      f"heredoc(s) across {scanned} script(s); nothing in them would be run")

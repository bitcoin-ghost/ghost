//! Errors for Ghost Lock construction.

use thiserror::Error;

/// Something went wrong building or describing a Lock.
#[derive(Debug, Error)]
pub enum LockError {
    /// A compartment rule was violated — see [`crate::compartment`].
    #[error("{0}")]
    Policy(String),

    /// A relative timelock exceeded the BIP-68 16-bit ceiling.
    #[error("relative timelock {blocks} exceeds the BIP-68 ceiling of {max} blocks; use an absolute CLTV height instead")]
    TimelockTooLong {
        /// The rejected value.
        blocks: u32,
        /// [`crate::constants::CSV_MAX_BLOCKS`].
        max: u32,
    },

    /// An inheritance height was not in the future relative to its anchor.
    #[error("inheritance height {height} is not beyond anchor height {anchor}")]
    InheritanceNotInFuture {
        /// The requested absolute height.
        height: u32,
        /// The height the Lock is being built at.
        anchor: u32,
    },

    /// The Taproot tree could not be assembled.
    #[error("taproot tree construction failed: {0}")]
    Taproot(String),
}

//! The node pool share-chain relay (W2.5).
//!
//! Nodes pass each other network shares (NS), anchors and the batches anchors lock in, and keep
//! the anchor chain with the most work. Membership is open: any node that speaks this protocol on
//! the same genesis is a peer; there is no roster and nothing is signed.
//!
//! - [`wire`]: message formats and size caps.
//! - [`relay`]: the transport-free core: receive and send paths, fork choice, credits.
//! - [`peers`]: rate limits, ban scores, the address book.
//! - [`headers`]: the Bitcoin header facts share checks need.
//! - [`net`]: the TCP transport that drives the core.
//! - [`client`]: a one-shot client that reads a node's advert and job stamps (W2.9).
//! - [`settlement`]: retiring what pool blocks paid into the stored ledger.
//! - [`archive`]: the Bitcoin block archive, stale branches included, that share checks and
//!   settlement read (W2.13).
//! - [`checkpoint`]: folded ledger state at a deep anchor (W2.13).
//! - [`relay::sync`]: initial sync, checkpoints, retention and pruning (W2.13).


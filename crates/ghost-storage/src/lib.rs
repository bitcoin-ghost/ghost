//! Ghost Storage - SQLite Database Layer
//!
//! This crate provides persistent storage for Bitcoin Ghost nodes:
//!
//! - **Shares**: Mining share records by round
//! - **Rounds**: Round metadata and payout info
//! - **Nodes**: Peer node registry and uptime
//! - **Miners**: Miner registry and statistics
//! - **Payouts**: Payout history and balances
//! - **Node Rewards**: Accumulated node reward ledger
//!
//! Uses SQLite with WAL mode for performance and crash safety.

pub mod audit_log;
pub mod database;
pub mod encryption;
pub mod migrations;
pub mod models;
pub mod mpc_lineage;
pub mod queries;
pub mod snapshot;

pub use audit_log::*;
pub use database::*;
pub use encryption::*;
pub use models::*;
pub use queries::BondRow;
pub use queries::GlyphRecord;
pub use queries::L2StateInfo;
pub use queries::{ConfidentialNoteRecord, ConfidentialTransferRecord};
pub use queries::{
    L2CheckpointRecord, L2EpochRecord, L2NoteRecord, L2NullifierRecord, L2ValidRootRecord,
};
pub use snapshot::*;

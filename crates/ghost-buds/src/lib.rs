//! BUDS (Bitcoin Unified Data Standard) Transaction Classification
//!
//! This crate provides transaction classification according to the BUDS standard:
//!
//! - **T0**: Core financial transactions (simple payments, standard P2WPKH/P2WSH)
//! - **T1**: Extended financial (multisig, timelocks, HTLCs, complex scripts)
//! - **T2**: Data-anchoring (small OP_RETURN ≤80 bytes for Lightning, commitments)
//! - **T3**: Heavy data (inscriptions, large witness, Runes, BRC-20)
//!
//! Each policy profile can choose which tiers to accept.

